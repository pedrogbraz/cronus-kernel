#![allow(dead_code, unused_imports, unused_variables)]
//! CRONUS Deploy Engine
//!
//! Generates deployment artifacts for a USER project (a directory of `*.cronus`
//! files): Dockerfile, docker-compose, .dockerignore, fly.toml, railway.json.
//! Images download the prebuilt `cronus` release binary pinned to the running
//! binary's version; they never need the kernel sources or a Rust toolchain.

use crate::cli::version::VERSION;

/// GitHub repository that publishes `cronus` release assets.
pub const RELEASE_REPO: &str = "pedrogbraz/cronus-kernel";

/// Linux target baked into container images (static musl binary: no glibc coupling).
pub const CONTAINER_TARGET: &str = "x86_64-unknown-linux-musl";

/// Directory inside the image holding persistent state (SQLite DB, `.cronus/`).
pub const DATA_DIR: &str = "/app/data";

/// Server command inside the image; the port comes from `$PORT`.
/// `--prod` disables internal routes, `--host 0.0.0.0` exposes the listener.
pub const RUN_COMMAND: &str = "cronus run --prod --host 0.0.0.0";

/// Release asset file name. Keep in sync with `.github/workflows/release.yml`
/// and `scripts/install.sh` (tests below check both).
pub fn release_asset_name(version: &str, target: &str) -> String {
    let ext = if target.ends_with("-windows-msvc") {
        "zip"
    } else {
        "tar.gz"
    };
    format!("cronus-{version}-{target}.{ext}")
}

pub fn release_asset_url(repo: &str, version: &str, target: &str) -> String {
    format!(
        "https://github.com/{repo}/releases/download/v{version}/{}",
        release_asset_name(version, target)
    )
}

const DOCKERFILE_BASE: &str = r##"# @TITLE@
# Generated by `cronus deploy`. The image downloads the prebuilt cronus @VERSION@
# binary from GitHub Releases and verifies its SHA256: no Rust toolchain and no
# kernel sources are needed. Pin another release with:
#   docker build --build-arg CRONUS_VERSION=x.y.z .

ARG CRONUS_VERSION=@VERSION@
ARG CRONUS_REPO=@REPO@

# ── Stage 1: fetch the release binary ──
FROM debian:bookworm-slim AS cronus
ARG CRONUS_VERSION
ARG CRONUS_REPO
ARG TARGETARCH
RUN apt-get update \
 && apt-get install -y --no-install-recommends ca-certificates curl \
 && rm -rf /var/lib/apt/lists/*
WORKDIR /tmp/cronus
RUN set -eu; \
    case "${TARGETARCH:-amd64}" in \
      amd64) target=@TARGET@ ;; \
      *) echo "cronus: no prebuilt linux/${TARGETARCH} binary; build with --platform linux/amd64" >&2; exit 1 ;; \
    esac; \
    version="${CRONUS_VERSION#v}"; \
    asset="cronus-${version}-${target}.tar.gz"; \
    base="https://github.com/${CRONUS_REPO}/releases/download/v${version}"; \
    curl -fsSLO "${base}/${asset}"; \
    curl -fsSLO "${base}/SHA256SUMS"; \
    awk -v a="${asset}" '$2 == a' SHA256SUMS > asset.sha256; \
    test -s asset.sha256; \
    sha256sum -c asset.sha256; \
    tar -xzf "${asset}"; \
    install -m 0755 "cronus-${version}-${target}/cronus" /usr/local/bin/cronus; \
    cronus --version

# ── Stage 2: runtime ──
FROM debian:bookworm-slim
RUN apt-get update \
 && apt-get install -y --no-install-recommends ca-certificates \
 && rm -rf /var/lib/apt/lists/* \
 && command -v setpriv >/dev/null \
 && groupadd --system --gid 10001 cronus \
 && useradd --system --uid 10001 --gid cronus --home-dir /app --no-create-home --shell /usr/sbin/nologin cronus \
 && mkdir -p /app/data/.cronus \
 && ln -s /app/data/.cronus /app/.cronus \
 && chown -R cronus:cronus /app
COPY --from=cronus /usr/local/bin/cronus /usr/local/bin/cronus
WORKDIR /app
"##;

const DOCKERFILE_PROJECT: &str = r##"
# Project sources and static assets (.dockerignore keeps local state and secrets out).
COPY --chown=cronus:cronus . /app/
"##;

const DOCKERFILE_RUNTIME: &str = r##"
# The SQLite database and runtime state (.cronus/ is symlinked here) must live
# on this volume: use `database sqlite "./data/app.db"` in the app block.
VOLUME ["/app/data"]
ENV PORT=@PORT@
EXPOSE @PORT@

# Volumes are often mounted root-owned (Fly, Railway). When started as root the
# entrypoint fixes /app/data ownership, then drops to the unprivileged `cronus`
# user (uid 10001) before exec'ing the server. `docker run --user 10001` skips it.
ENTRYPOINT ["/bin/sh", "-c", "set -eu; mkdir -p /app/data/.cronus; if [ \"$(id -u)\" = 0 ]; then chown -R cronus:cronus /app/data; exec setpriv --reuid=cronus --regid=cronus --init-groups \"$@\"; fi; exec \"$@\"", "cronus-entrypoint"]
CMD ["sh", "-c", "exec @RUN@ \"${PORT}\""]
"##;

fn one_line(s: &str) -> String {
    s.chars()
        .map(|c| if c.is_control() { ' ' } else { c })
        .collect()
}

fn render_dockerfile(title: &str, port: u16, project_section: &str) -> String {
    let template = format!("{DOCKERFILE_BASE}{project_section}{DOCKERFILE_RUNTIME}");
    template
        .replace("@TITLE@", &one_line(title))
        .replace("@VERSION@", VERSION)
        .replace("@REPO@", RELEASE_REPO)
        .replace("@TARGET@", CONTAINER_TARGET)
        .replace("@RUN@", RUN_COMMAND)
        .replace("@PORT@", &port.to_string())
}

/// Dockerfile for a user project: release binary + the project directory.
pub fn generate_dockerfile(app_name: &str, port: u16) -> String {
    render_dockerfile(
        &format!("{app_name} — CRONUS app image"),
        port,
        DOCKERFILE_PROJECT,
    )
}

/// Dockerfile with only the release binary; `.cronus` sources are mounted at
/// run time (microservices compose).
pub fn generate_service_dockerfile(port: u16) -> String {
    render_dockerfile("CRONUS service image", port, "")
}

/// Warning when the app's SQLite file would not land on the persistent volume.
pub fn database_outside_volume(db_path: Option<&str>) -> Option<String> {
    let raw = db_path.unwrap_or("data.db");
    let rel = raw.trim_start_matches("./");
    if rel.starts_with("data/") || raw.starts_with("/app/data/") {
        return None;
    }
    Some(format!(
        "database path \"{raw}\" is outside the persistent volume ({DATA_DIR}); \
         set `database sqlite \"./data/app.db\"` in the app block or the data is lost on redeploy"
    ))
}

pub fn generate_compose(app_name: &str, port: u16) -> String {
    let mut slug = slugify(app_name);
    if slug.is_empty() {
        slug = "cronus-app".into();
    }
    format!(
        r#"# {title} — docker compose
# Start with: docker compose up --build

services:
  app:
    build:
      context: .
      args:
        CRONUS_VERSION: "{VERSION}"
    container_name: {slug}
    ports:
      - "{port}:{port}"
    environment:
      PORT: "{port}"
      # Uncomment to pass a secret of at least 32 bytes from your shell; otherwise
      # one is generated and kept in the data volume (.cronus/jwt.key).
      # JWT_SECRET: "${{JWT_SECRET:?set JWT_SECRET}}"
    volumes:
      - cronus-data:{DATA_DIR}
    restart: unless-stopped

volumes:
  cronus-data:
"#,
        title = one_line(app_name),
    )
}

