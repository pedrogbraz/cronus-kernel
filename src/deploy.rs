    #[cfg(unix)]
    fn installer_dry_run(envs: &[(&str, &str)]) -> std::process::Output {
        let script = concat!(env!("CARGO_MANIFEST_DIR"), "/scripts/install.sh");
        let mut cmd = std::process::Command::new("sh");
        cmd.arg(script)
            .env_clear()
            .env("PATH", std::env::var("PATH").unwrap_or_default())
            .env("HOME", "/home/tester")
            .env("CRONUS_INSTALL_DRY_RUN", "1");
        for (k, v) in envs {
            cmd.env(k, v);
        }
        cmd.output().expect("run sh scripts/install.sh")
    }

    #[cfg(unix)]
    #[test]
    fn install_script_dry_run_resolves_release_assets() {
        let cases = [
            ("Darwin", "arm64", "aarch64-apple-darwin"),
            ("Darwin", "x86_64", "x86_64-apple-darwin"),
            ("Linux", "x86_64", "x86_64-unknown-linux-musl"),
            ("Linux", "amd64", "x86_64-unknown-linux-musl"),
        ];
        for (os, arch, target) in cases {
            let out = installer_dry_run(&[
                ("CRONUS_OS", os),
                ("CRONUS_ARCH", arch),
                ("CRONUS_VERSION", "v1.2.3"),
                ("CRONUS_REPO", "acme/cronus"),
            ]);
            let stdout = String::from_utf8_lossy(&out.stdout);
            assert!(
                out.status.success(),
                "{os}/{arch}: {}",
                String::from_utf8_lossy(&out.stderr)
            );
            let url = release_asset_url("acme/cronus", "1.2.3", target);
            assert!(stdout.contains(&format!("asset_url={url}\n")), "{stdout}");
            assert!(stdout.contains(&format!("target={target}\n")), "{stdout}");
            assert!(stdout.contains(
                "checksums_url=https://github.com/acme/cronus/releases/download/v1.2.3/SHA256SUMS\n"
            ));
            assert!(stdout.contains("install_path=/home/tester/.cronus/bin/cronus\n"));
        }
    }

    #[cfg(unix)]
    #[test]
    fn install_script_dry_run_overrides_and_errors() {
        let out = installer_dry_run(&[
            ("CRONUS_TARGET", "x86_64-unknown-linux-gnu"),
            ("CRONUS_INSTALL_DIR", "/opt/tools"),
            ("CRONUS_VERSION", "0.9.0"),
        ]);
        let stdout = String::from_utf8_lossy(&out.stdout);
        assert!(out.status.success());
        let url = release_asset_url(RELEASE_REPO, "0.9.0", "x86_64-unknown-linux-gnu");
        assert!(stdout.contains(&format!("asset_url={url}\n")), "{stdout}");
        assert!(stdout.contains("install_path=/opt/tools/cronus\n"));

        let latest = installer_dry_run(&[("CRONUS_OS", "Linux"), ("CRONUS_ARCH", "x86_64")]);
        assert!(latest.status.success());
        assert!(String::from_utf8_lossy(&latest.stdout).contains("version=latest\n"));

        for (os, arch) in [
            ("Linux", "aarch64"),
            ("FreeBSD", "amd64"),
            ("MINGW64_NT-10.0", "x86_64"),
        ] {
            let out = installer_dry_run(&[("CRONUS_OS", os), ("CRONUS_ARCH", arch)]);
            assert!(!out.status.success(), "{os}/{arch} should fail");
            assert!(String::from_utf8_lossy(&out.stderr).contains("cronus-install: error:"));
            assert!(!String::from_utf8_lossy(&out.stdout).contains("asset_url="));
        }
    }
